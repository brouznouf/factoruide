//! The addon's data file: every route as Lua tables.

use super::phrase::Arg;
use super::types::{Route, RouteProfession, Step, TargetKind};
use std::fmt::Write as _;

pub fn lua_str(s: &str) -> String {
    format!("{s:?}")
}

/// Professions as the addon reads them: key, name, skill line, target, start and curve.
fn lua_professions(professions: &[RouteProfession]) -> String {
    (professions.iter())
        .map(|p| {
            format!(
                "{{ key = {}, name = {}, line = {}, target = {}, start = {}, curve = {{ {} }} }}",
                lua_str(&p.key),
                lua_str(&p.name),
                p.skill_line,
                p.target,
                p.start,
                p.curve.iter().map(ToString::to_string).collect::<Vec<_>>().join(", ")
            )
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// How many of its item an item objective asks for (the number of its sentence).
fn item_count(s: &Step) -> Option<i64> {
    if s.target.as_ref()?.kind != TargetKind::Item {
        return None;
    }
    s.say.iter().find_map(|p| match p.args.get("n") {
        Some(Arg::Num(n)) => Some(*n),
        _ => None,
    })
}

/// Lua data file for the addon, holding every given route.
pub fn to_lua(routes: &[Route]) -> String {
    let mut out =
        String::from("-- Generated by `fg route`. Do not edit.\nlocal FG = Factoruide\nFG.Routes = FG.Routes or {}\n");
    for r in routes {
        // A group guide: its players (the steps' `mb` bits and `gp` pairs are in this order).
        let players = if r.players.is_empty() {
            String::new()
        } else {
            format!(
                " players = {{ {} }}, syncMax = {},",
                r.players
                    .iter()
                    .map(|p| format!(
                        "{{ n = {}, race = {}, class = {}, professions = {{ {} }} }}",
                        lua_str(&p.name),
                        p.race_id,
                        p.class_id,
                        lua_professions(&p.professions)
                    ))
                    .collect::<Vec<_>>()
                    .join(", "),
                r.sync_max.unwrap_or(1.0)
            ) + &format!(
                " classSpells = {{ {} }},",
                r.class_spells
                    .iter()
                    .map(|(c, ids)| format!(
                        "[{c}] = {{ {} }}",
                        ids.iter().map(ToString::to_string).collect::<Vec<_>>().join(", ")
                    ))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        let _ = writeln!(
            out,
            "FG.Routes[{}] = {{ race = {}, class = {}, faction = {}, locale = {}, fromLevel = {}, toLevel = {}, time = {}, levels = {{ {} }}, professions = {{ {} }}, reputations = {{ {} }}, spells = {{ {} }}, checkpoints = {{ {} }},{players} steps = {{",
            lua_str(&r.name),
            r.race_id,
            r.class_id,
            lua_str(r.faction.name()),
            lua_str(r.locale.as_deref().unwrap_or("enUS")),
            r.from_level,
            r.to_level,
            r.total_time,
            // Planned play time (seconds) on reaching each level: [level] = time.
            (r.from_level + 1..=r.to_level)
                .filter_map(|l| r
                    .steps
                    .iter()
                    .find(|s| s.level >= l)
                    .map(|s| format!("[{l}] = {}", s.time.round())))
                .collect::<Vec<_>>()
                .join(", "),
            lua_professions(&r.professions),
            // Reputation goals: points from the bottom of Neutral, where the guide gets to.
            r.reputation
                .iter()
                .map(|g| format!(
                    "{{ id = {}, name = {}, target = {}, reached = {} }}",
                    g.faction,
                    lua_str(&g.name),
                    g.target,
                    g.reached
                ))
                .collect::<Vec<_>>()
                .join(", "),
            r.spells.iter().map(ToString::to_string).collect::<Vec<_>>().join(", "),
            // Lua indexes from 1.
            r.checkpoints
                .iter()
                .map(|c| format!("{{ lvl = {}, step = {} }}", c.level, c.step + 1))
                .collect::<Vec<_>>()
                .join(", ")
        );
        // Steps carry the time they are planned to take (`d`, seconds): `time` is when each is done.
        let mut previous = 0.0;
        for s in &r.steps {
            let duration = (s.time - previous).max(0.0).round();
            previous = s.time;
            let mut fields = vec![
                format!("k = {}", lua_str(s.kind.as_str())),
                format!("t = {}", lua_str(&s.text)),
            ];
            if let Some(q) = s.quest {
                fields.push(format!("q = {q}"));
            }
            if s.bg {
                fields.push("bg = true".into());
            }
            if s.try_buy {
                fields.push("tr = true".into());
            }
            if s.buy {
                fields.push("by = true".into());
            }
            if s.inside {
                fields.push("di = true".into());
            }
            if s.held {
                fields.push("hd = true".into());
            }
            // Mobs on the way: their number (addons before the XP count) and their XP.
            if let Some(n) = s.farm {
                fields.push(format!("fk = {n}"));
            }
            if let Some(xp) = s.farm_xp {
                fields.push(format!("fx = {xp}"));
            }
            if !s.alt.is_empty() {
                fields.push(format!(
                    "alt = {{ {} }}",
                    s.alt.iter().map(ToString::to_string).collect::<Vec<_>>().join(", ")
                ));
            }
            for (key, ids) in [("pre", &s.pre), ("pa", &s.pre_any)] {
                if !ids.is_empty() {
                    fields.push(format!(
                        "{key} = {{ {} }}",
                        ids.iter().map(ToString::to_string).collect::<Vec<_>>().join(", ")
                    ));
                }
            }
            if let Some(l) = s.min_level {
                fields.push(format!("min = {l}"));
            }
            if let Some(o) = s.objective {
                fields.push(format!("o = {}", o + 1));
            }
            if let Some(m) = &s.map {
                fields.push(format!("m = {}, x = {}, y = {}", m.ui_map, m.x, m.y));
            }
            // The walk to it (world x, y): where it starts and turns, for the compass.
            // The guide keeps the whole walk; the addon gets it lightened (the only place it is).
            let walk = lighten_walk(s);
            if !walk.is_empty() {
                fields.push(format!(
                    "wp = {{ {} }}",
                    walk.iter()
                        .map(|[x, y]| format!("{x}, {y}"))
                        .collect::<Vec<_>>()
                        .join(", ")
                ));
            }
            // Its NPC patrols: the spots are along its path, the nearest pointed at first.
            if s.patrol {
                fields.push("pt = true".into());
            }
            if !s.spots.is_empty() {
                fields.push(format!(
                    "spots = {{ {} }}",
                    s.spots
                        .iter()
                        .map(|p| format!("{{ m = {}, x = {}, y = {} }}", p.ui_map, p.x, p.y))
                        .collect::<Vec<_>>()
                        .join(", ")
                ));
            }
            if let Some(t) = &s.target {
                fields.push(format!(
                    "e = {}, id = {}, n = {}",
                    lua_str(t.kind.as_str()),
                    t.id,
                    lua_str(&t.name)
                ));
            }
            if let Some(c) = s.child {
                fields.push(format!("cq = {c}"));
            }
            if let Some(n) = item_count(s) {
                fields.push(format!("c = {n}"));
            }
            if let Some(sk) = s.skill {
                fields.push(format!("sk = {sk}"));
            }
            if let Some(line) = s.line {
                fields.push(format!("line = {line}"));
            }
            if s.elite {
                fields.push("el = true".into());
            }
            if let Some(l) = s.mob_level {
                fields.push(format!("ml = {l}"));
            }
            if !s.mobs.is_empty() {
                fields.push(format!(
                    "mobs = {{ {} }}",
                    s.mobs.iter().map(|m| lua_str(m)).collect::<Vec<_>>().join(", ")
                ));
            }
            // Their IDs: the addon does not count them as mobs on the way.
            if !s.mob_ids.is_empty() {
                fields.push(format!(
                    "mi = {{ {} }}",
                    s.mob_ids.iter().map(ToString::to_string).collect::<Vec<_>>().join(", ")
                ));
            }
            if let Some(item) = s.reward {
                fields.push(format!("rw = {item}"));
            }
            if let Some(xp) = s.reward_xp {
                fields.push(format!("rx = {xp}"));
            }
            if !s.spells.is_empty() {
                fields.push(format!(
                    "sp = {{ {} }}",
                    s.spells.iter().map(ToString::to_string).collect::<Vec<_>>().join(", ")
                ));
            }
            if s.keep {
                fields.push("kp = true".into());
            }
            fields.push(format!("lvl = {}", s.level));
            if duration >= 1.0 {
                fields.push(format!("d = {duration}"));
            }
            if let Some(xp) = s.route_xp {
                fields.push(format!("px = {xp}"));
            }
            if let Some(xp) = s.xp {
                fields.push(format!("xp = {xp}"));
            }
            // In a group: the players it is for when not everyone, where each one is once it is done.
            if let Some(m) = s.members {
                fields.push(format!("mb = {m}"));
            }
            if !s.party.is_empty() {
                fields.push(format!(
                    "gp = {{ {} }}",
                    s.party
                        .iter()
                        .map(|(l, x)| format!("{l}, {x}"))
                        .collect::<Vec<_>>()
                        .join(", ")
                ));
            }
            let _ = writeln!(out, "  {{ {} }},", fields.join(", "));
        }
        out.push_str("} }\n");
    }
    out
}

/// Yards a walk may stray from the one the guide keeps once written for the addon.
const WALK_TOLERANCE: f64 = 6.0;

/// The walk of a step for the addon: its points farther than `WALK_TOLERANCE` from the line
/// between their neighbours (Douglas-Peucker, the step's place the last end), in whole yards.
/// This is the only place a walk is simplified.
fn lighten_walk(step: &Step) -> Vec<[f64; 2]> {
    fn keep(path: &[[f64; 2]], out: &mut Vec<[f64; 2]>) {
        let (a, b) = (path[0], path[path.len() - 1]);
        let (dx, dy) = (b[0] - a[0], b[1] - a[1]);
        let len = dx.hypot(dy);
        let far = (1..path.len() - 1)
            .map(|i| {
                let p = path[i];
                let d = if len < 1e-9 {
                    (p[0] - a[0]).hypot(p[1] - a[1])
                } else {
                    ((p[0] - a[0]) * dy - (p[1] - a[1]) * dx).abs() / len
                };
                (i, d)
            })
            .max_by(|x, y| x.1.total_cmp(&y.1));
        match far {
            Some((i, d)) if d > WALK_TOLERANCE => {
                keep(&path[..=i], out);
                out.pop();
                keep(&path[i..], out);
            }
            _ => {
                out.push(a);
                out.push(b);
            }
        }
    }
    let Some(end) = step.world else {
        return step.path.clone();
    };
    let mut path = step.path.clone();
    path.push([end[1], end[2]]);
    let mut kept = Vec::new();
    if path.len() > 2 {
        keep(&path, &mut kept);
    } else {
        kept = path;
    }
    kept.pop();
    kept.iter().map(|[x, y]| [x.round(), y.round()]).collect()
}
