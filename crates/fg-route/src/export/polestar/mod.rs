    fn steps(lua: &str) -> Vec<Vec<String>> {
        let mut out: Vec<Vec<String>> = Vec::new();
        for line in lua.lines() {
            if line.starts_with("\t\t\t{ ") {
                out.push(Vec::new());
            } else if line.starts_with("\t\t\t\t{ ") {
                out.last_mut().unwrap().push(line.trim().to_owned());
            }
        }
        out
    }

