/// How a goal joins the others.
#[derive(Clone, Copy, PartialEq)]
enum Join {
    /// A travel or a note: goes in the step of the goal after it.
    Before,
    /// At an NPC or object (by kind and ID): with the goals before it at the same one.
    At(TargetKind, i64),
    /// A step of its own.
    Alone,
}

/// A field's value.
enum Val {
    Str(String),
    /// A number or `true`, as written.
    Num(String),
    List(Vec<Val>),
    /// Its fields in their order.
    Obj(Vec<(&'static str, Val)>),
}

impl Val {
    fn lua(&self) -> String {
        match self {
            Val::Str(s) => lua(s),
            Val::Num(s) => s.clone(),
            Val::List(items) => {
                let items: Vec<String> = items.iter().map(Val::lua).collect();
                format!("{{ {} }}", items.join(", "))
            }
            Val::Obj(fields) => {
                let fields: Vec<String> = fields.iter().map(|(k, v)| format!("{k} = {}", v.lua())).collect();
                format!("{{ {} }}", fields.join(", "))
            }
        }
    }

    fn json(&self) -> serde_json::Value {
        match self {
            Val::Str(s) => s.as_str().into(),
            Val::Num(s) => serde_json::from_str(s).unwrap_or_else(|_| s.as_str().into()),
            Val::List(items) => items.iter().map(Val::json).collect(),
            Val::Obj(fields) => fields.iter().map(|(k, v)| ((*k).to_owned(), v.json())).collect(),
        }
    }
}

fn num(value: impl std::fmt::Display) -> Val {
    Val::Num(value.to_string())
}

/// A goal of Polestar's (`t` its verb), its fields in their order: written as a Lua table in the
/// pack, as a line in a guide's source (`source`).
struct Goal {
    verb: &'static str,
    fields: Vec<(&'static str, Val)>,
    join: Join,
    /// The step's title when it starts one.
    title: Option<String>,
}

impl Goal {
    fn new(verb: &'static str, join: Join) -> Self {
        Self {
            verb,
            fields: Vec::new(),
            join,
            title: None,
        }
    }

    fn str(mut self, key: &'static str, value: &str) -> Self {
        self.fields.push((key, Val::Str(value.to_owned())));
        self
    }

    fn num(mut self, key: &'static str, value: impl std::fmt::Display) -> Self {
        self.fields.push((key, Val::Num(value.to_string())));
        self
    }

    fn ids(mut self, key: &'static str, ids: &[i64]) -> Self {
        if !ids.is_empty() {
            self.fields.push((key, Val::List(ids.iter().map(num).collect())));
        }
        self
    }

    fn place(self, step: &Step) -> Self {
        match &step.map {
            Some(m) => self.num("map", m.ui_map).num("x", pct(m.x)).num("y", pct(m.y)),
            None => self,
        }
    }

    /// A field's value as written (a string unquoted; none for a table).
    fn get(&self, key: &str) -> Option<&str> {
        self.fields.iter().find(|(k, _)| *k == key).and_then(|(_, v)| match v {
            Val::Str(s) | Val::Num(s) => Some(s.as_str()),
            Val::List(_) | Val::Obj(_) => None,
        })
    }

    /// The Lua table's fields, `t` first.
    fn lua_fields(&self) -> Vec<String> {
        std::iter::once(format!("t = {}", lua(self.verb)))
            .chain(self.fields.iter().map(|(k, v)| format!("{k} = {}", v.lua())))
            .collect()
    }

    fn json(&self) -> serde_json::Value {
        std::iter::once(("t".to_owned(), self.verb.into()))
            .chain(self.fields.iter().map(|(k, v)| ((*k).to_owned(), v.json())))
            .collect::<serde_json::Map<_, _>>()
            .into()
    }

    /// Where its mobs are when they live in several places: its own place, then the others on
    /// its map as alternatives (Polestar leads to the place of the guide, and on to another by
    /// hand). A patrolling NPC's places along its path: Polestar leads to the closest.
    fn spots(mut self, step: &Step) -> Self {
        /// Radius of a place (yards).
        const RADIUS: u32 = 40;
        let Some(m) = &step.map else { return self };
        let others: Vec<_> = step.spots.iter().filter(|p| p.ui_map == m.ui_map).collect();
        if !others.is_empty() {
            let spot = |x: f64, y: f64, alt: bool| {
                let mut fields = vec![("x", num(pct(x))), ("y", num(pct(y))), ("r", num(RADIUS))];
                if alt {
                    fields.push(("alt", num(true)));
                }
                Val::Obj(fields)
            };
            let spots = std::iter::once(spot(m.x, m.y, false))
                .chain(others.iter().map(|p| spot(p.x, p.y, !step.patrol)))
                .collect();
            self.fields.push(("spots", Val::List(spots)));
        }
        self
    }

    fn text(self, step: &Step) -> Self {
        let text = step.text.trim();
        if text.is_empty() { self } else { self.str("text", text) }
    }
}

/// A map coordinate as Polestar takes it, from 0 to 100: a place just past the map's edge (a
/// hive under Silithus) on the edge, rather than the whole guide refused.
fn pct(v: f64) -> f64 {
    v.clamp(0.0, 100.0)
}

/// A name, else the step's text, its quest, its kind: Polestar refuses a whole guide for one
/// empty name.
fn name_or<'a>(name: &'a str, step: &'a Step) -> &'a str {
    [name, &step.text, step.quest_name.as_deref().unwrap_or("")]
        .into_iter()
        .map(str::trim)
        .find(|n| !n.is_empty())
        .unwrap_or(step.kind.as_str())
}

/// Where a step takes place as Polestar names places: a flight path's town ("Sentinel Hill",
/// not "Sentinel Hill, Westfall").
fn town(name: &str) -> &str {
    name.split(',').next().unwrap_or(name).trim()
}

/// The number of things an objective counts (its sentence's `n`).
fn count(step: &Step) -> Option<i64> {
    step.say.iter().find_map(|p| match p.args.get("n") {
        Some(Arg::Num(n)) => Some(*n),
        _ => None,
    })
}

/// A goal going to the step's place (a note where it has none), before the next goal.
fn travel(step: &Step) -> Goal {
    if step.map.is_some() {
        Goal::new("goto", Join::Before).place(step).text(step)
    } else {
        note(step)
    }
}

fn note(step: &Step) -> Goal {
    Goal::new("note", Join::Before).str("text", name_or("", step))
}

/// The goals of a step of the guide (a grind: going there, then the level).
fn goals(step: &Step) -> Vec<Goal> {
    let target = step.target.as_ref();
    let at = target.map_or(Join::Alone, |t| Join::At(t.kind, t.id));
    let title = step.quest_name.as_deref().unwrap_or("");
    // Who gives or takes a quest.
    let source = |goal: Goal| match target {
        Some(t) if t.kind == TargetKind::Npc => goal.num("npc", t.id).str("npcName", name_or(&t.name, step)),
        Some(t) if t.kind == TargetKind::Object => goal.num("object", t.id).str("objName", name_or(&t.name, step)),
        Some(t) if t.kind == TargetKind::Item => goal.num("item", t.id).str("itemName", name_or(&t.name, step)),
        _ => goal,
    };
    let quest = |goal: Goal| match step.quest {
        Some(q) => goal.num("quest", q).str("title", name_or(title, step)),
        None => goal,
    };
    let goal = match step.kind {
        // A book for the library: got here, the quest is taken with its turn-in.
        StepKind::Accept
            if step.held
                && let Some(t) = target =>
        {
            Goal::new("collect", Join::Alone)
                .num("item", t.id)
                .str("itemName", name_or(&t.name, step))
        }
        StepKind::Accept if step.quest.is_some() => {
            let mut goal = source(quest(Goal::new("accept", at)))
                .ids("pre", &step.pre_any)
                .ids("preAll", &step.pre)
                .ids("closedBy", &step.alt);
            if let Some(l) = step.min_level {
                goal = goal.num("minLevel", l);
            }
            // A profession quest: taken only with the skill.
            if step.skill.is_some() {
                goal = goal.num("optional", true);
            }
            goal
        }
        StepKind::TurnIn if step.say.first().is_some_and(|p| p.key == "turnin.held") => {
            return ["accept", "turnin"]
                .map(|kind| {
                    let mut goal = source(quest(Goal::new(kind, at))).text(step).place(step);
                    goal.title = target.map(|t| t.name.clone());
                    goal
                })
                .into();
        }
        StepKind::TurnIn if step.quest.is_some() => source(quest(Goal::new("turnin", at))),
        // A child quest handed in on the way to its parent's turn-in (Distracting Jarven): a
        // hand-in straight from the window, with no accept.
        StepKind::Objective if let Some(child) = step.child => source(
            Goal::new("turnin", at)
                .num("quest", child)
                .str("title", name_or(step.child_name.as_deref().unwrap_or(""), step))
                .num("direct", true),
        ),
        StepKind::Objective if step.quest.is_some() => objective(step, target, quest),
        StepKind::Bind | StepKind::Sell => match target {
            Some(t) if t.kind == TargetKind::Npc => Goal::new("talk", at)
                .num("npc", t.id)
                .str("npcName", name_or(&t.name, step)),
            _ => travel(step),
        },
        StepKind::Train => match target {
            Some(t) => Goal::new("train", at)
                .num("npc", t.id)
                .str("npcName", name_or(&t.name, step)),
            None => travel(step),
        },
        // Done once the player is there, the place named by the game in its language (`area`).
        StepKind::Hearth => match step.zone.as_deref() {
            Some(zone) => {
                let goal = Goal::new("hearth", Join::Before).str("location", zone);
                match step.zone_id {
                    Some(area) => goal.num("area", area),
                    None => goal,
                }
            }
            None => travel(step),
        },
        // Flight points by their node, which Polestar names in the game's language.
        StepKind::Fly => match target {
            Some(t) => Goal::new("fly", Join::Before)
                .str("location", town(&t.name))
                .num("node", t.id),
            None => travel(step),
        },
        StepKind::FlightMaster => match target {
            Some(t) => Goal::new("getfp", Join::Alone)
                .str("location", town(&t.name))
                .num("node", t.id),
            None => travel(step),
        },
        // Grinding to a level, or (`xp`) into it: the place, then the level when it is one.
        StepKind::Grind => {
            if step.xp.is_some() {
                travel(step)
            } else {
                let level = Goal::new("level", Join::Alone).num("level", step.level);
                return if step.map.is_some() {
                    vec![travel(step), level]
                } else {
                    vec![level.text(step)]
                };
            }
        }
        StepKind::Abandon => note(step),
        _ => travel(step),
    };
    let mut goal = if matches!(goal.join, Join::Before) || has_text(&goal) {
        goal
    } else {
        goal.text(step)
    };
    if !matches!(goal.join, Join::Before) {
        goal = goal.place(step).spots(step);
        // A quest only characters with a profession can take: hidden from the others.
        if let (Some(_), Some(line), Some(skill)) = (step.quest, step.line, step.skill) {
            goal = goal.num("profLine", line).num("profRank", skill);
        }
        // Elite mobs: Polestar says a group is advised.
        if step.elite && step.kind == StepKind::Objective {
            goal.fields.push((
                "group",
                Val::Obj(vec![("kind", Val::Str("elite".to_owned())), ("rank", num(1))]),
            ));
        }
        goal.title = target
            .filter(|t| matches!(t.kind, TargetKind::Npc | TargetKind::Object))
            .map(|t| t.name.clone())
            .or_else(|| step.zone.clone());
    }
    vec![goal]
}

fn has_text(goal: &Goal) -> bool {
    goal.get("text").is_some()
}

/// A quest objective: killing, getting, using an object or buying, else (talking, an area, an
/// event) counted as the objective goes.
fn objective(step: &Step, target: Option<&super::Target>, quest: impl Fn(Goal) -> Goal) -> Goal {
    let Some(k) = step.objective else {
        // Several objectives: done with the quest.
        return quest(Goal::new("complete", Join::Alone));
    };
    let key = step.say.first().map_or("", |p| p.key.as_str());
    let name = |t: &super::Target| name_or(&t.name, step).to_owned();
    let goal = match target {
        // Guides of the first format have no sentences: their NPCs are to kill.
        Some(t) if t.kind == TargetKind::Npc && (key == "objective.kill" || key.is_empty()) => {
            Goal::new("kill", Join::Alone).str("target", &name(t)).num("npc", t.id)
        }
        Some(t) if t.kind == TargetKind::Item && key == "objective.buy" => Goal::new("buy", Join::Alone)
            .num("item", t.id)
            .str("itemName", &name(t)),
        Some(t) if t.kind == TargetKind::Item => Goal::new("collect", Join::Alone)
            .num("item", t.id)
            .str("itemName", &name(t)),
        Some(t) if t.kind == TargetKind::Object => Goal::new("interact", Join::Alone)
            .num("object", t.id)
            .str("objName", &name(t)),
        _ => Goal::new("kill", Join::Alone).str("target", name_or("", step)),
    };
    // Polestar counts one by default.
    let goal = match count(step) {
        Some(n) if n > 1 => goal.num("count", n),
        _ => goal,
    };
    let mut goal = match step.slot.map_or(u32::from(k) + 1, u32::from) {
        // An item the quest only uses: binding it to an objective would count it there.
        0 if target.is_some_and(|t| t.kind == TargetKind::Item) => goal,
        0 => quest(goal),
        oi => quest(goal).num("oi", oi),
    };
    // Done along the way while doing other quests: never holds the guide.
    if step.bg {
        goal = goal.num("optional", true);
    }
    goal
}

/// The title of a step whose goals are at several places: the quest most of them serve, when
/// at least two do.
fn shared_title(goals: &[Goal]) -> Option<String> {
    let mut counts: Vec<(&str, usize)> = Vec::new();
    for quest in goals.iter().filter_map(|g| g.get("quest")) {
        match counts.iter_mut().find(|(q, _)| *q == quest) {
            Some((_, n)) => *n += 1,
            None => counts.push((quest, 1)),
        }
    }
    let best = counts.iter().map(|(_, n)| *n).max().filter(|n| *n >= 2)?;
    let (quest, _) = counts.iter().find(|(_, n)| *n == best)?;
    goals
        .iter()
        .find(|g| g.get("quest") == Some(quest))
        .and_then(|g| g.get("title"))
        .map(str::to_owned)
}

/// The steps of Polestar's guide: each a title and its goals.
///
/// An objective done along the way is optional and never holds the guide: before the turn-in
/// of a quest with such objectives, a step of its own holds it until the quest is complete
/// (otherwise Polestar shows the turn-in while the objectives are not done: Naga at the Zoram
/// Strand before the 20 Wrathtail Heads).
fn plan(route: &Route) -> Vec<(Option<String>, Vec<Goal>)> {
    let mut steps: Vec<(Option<String>, Vec<Goal>)> = Vec::new();
    let mut before: Vec<Goal> = Vec::new();
    let mut last: Option<Join> = None;
    // Whether the last step took goals of steps around the same place (`groups`).
    let mut grouped: Vec<bool> = Vec::new();
    // Quests with optional objectives, by ID as written.
    let mut along: Vec<String> = Vec::new();
    for (step, joins_group) in route.steps.iter().zip(crate::export::groups::joins(&route.steps)) {
        // Whether this step's goals may join the last step for being around the same place.
        let mut open = joins_group;
        for goal in goals(step) {
            let quest = goal.get("quest").map(str::to_owned);
            if goal.get("oi").is_some() && goal.get("optional").is_some() {
                along.extend(quest.clone().filter(|q| !along.contains(q)));
            }
            if goal.verb == "turnin"
                && goal.get("direct").is_none()
                && let Some(q) = quest.filter(|q| along.contains(q))
            {
                along.retain(|a| *a != q);
                let mut complete = Goal::new("complete", Join::Alone).num("quest", &q);
                if let Some(title) = goal.get("title") {
                    complete = complete.str("title", title);
                }
                complete.title = goal.get("title").map(str::to_owned);
                steps.push((complete.title.clone(), vec![complete]));
                grouped.push(false);
                last = None;
                // The turn-in goes after the step holding it, never in it.
                open = false;
            }
            if goal.join == Join::Before {
                before.push(goal);
                continue;
            }
            let at_last = matches!(goal.join, Join::At(..)) && last == Some(goal.join);
            let level = goal.verb == "level";
            let by_place = !at_last && !level && open;
            let joins = before.is_empty() && (at_last || by_place);
            last = Some(goal.join);
            if joins && let Some(last) = steps.last_mut() {
                last.1.push(goal);
                if by_place && let Some(g) = grouped.last_mut() {
                    *g = true;
                }
            } else {
                let mut all = std::mem::take(&mut before);
                let title = goal.title.clone();
                all.push(goal);
                steps.push((title, all));
                grouped.push(false);
                // The step's other goals are at its place.
                open = true;
            }
            // A grind holds its step until the level: nothing else joins it.
            if level {
                open = false;
            }
        }
    }
    if !before.is_empty() {
        steps.push((None, before));
        grouped.push(false);
    }
    for ((title, goals), grouped) in steps.iter_mut().zip(grouped) {
        if grouped && let Some(shared) = shared_title(goals) {
            *title = Some(shared);
        }
    }
    steps
}

/// A guide's definition as `RegisterGuide` takes it, but its steps.
fn definition(id: &str, route: &Route, version: u32) -> Vec<(&'static str, Val)> {
    let mut def = vec![
        ("id", Val::Str(format!("{PACK_ID}/{id}"))),
        ("title", Val::Str(route.name.clone())),
        ("faction", Val::Str(route.faction.name().to_owned())),
    ];
    if let Some(race) = race_file(route.race_id) {
        def.push(("races", Val::List(vec![Val::Str(race.to_owned())])));
    }
    if let Some(class) = class_file(route.class_id) {
        def.push(("classes", Val::List(vec![Val::Str(class.to_owned())])));
    }
    def.extend([
        ("minLevel", num(route.from_level)),
        ("maxLevel", num(route.to_level)),
        ("category", Val::Str("Leveling".to_owned())),
        ("author", Val::Str("Factoruide".to_owned())),
        ("version", num(version)),
    ]);
    def
}

/// One guide's `RegisterGuide`, in a function of its own.
fn guide(id: &str, route: &Route) -> String {
    let steps = plan(route);
    if steps.is_empty() {
        return String::new();
    }
    let mut def = definition(id, route, 1);
    def.insert(1, ("pack", Val::Str(PACK_ID.to_owned())));
    let def: Vec<String> = def.iter().map(|(k, v)| format!("{k} = {}", v.lua())).collect();
    let mut out = format!(
        "\ndo\n\tlocal function register()\n\t\tPolestar.RegisterGuide({{ {}, steps = {{\n",
        def.join(", ")
    );
    for (title, goals) in &steps {
        out.push_str("\t\t\t{ ");
        if let Some(title) = title.as_deref().filter(|t| !t.trim().is_empty()) {
            let _ = write!(out, "title = {}, ", lua(title));
        }
        out.push_str("goals = {\n");
        for goal in goals {
            let _ = writeln!(out, "\t\t\t\t{{ {} }},", goal.lua_fields().join(", "));
        }
        out.push_str("\t\t\t} },\n");
    }
    out.push_str("\t\t} })\n\tend\n\tregister()\nend\n");
    out
}

/// What Polestar's Import page takes today: more and it refuses the string.
pub(crate) const IMPORT_MAX_STEPS: usize = 60;
pub(crate) const IMPORT_MAX_CHARS: usize = 50_000;
pub(crate) const IMPORT_MAX_BYTES: usize = 262_144;

/// A guide as an import string for Polestar's Import page (`/polestar import`).
#[derive(Debug, serde::Serialize)]
pub struct ImportString {
    pub text: String,
    pub steps: usize,
    /// The guide data, decompressed (bytes).
    pub bytes: usize,
    /// Within what Polestar takes today.
    pub fits: bool,
}

/// `!PS1!<Adler-32 of the JSON>!<base64 of the JSON compressed with zlib>`, the JSON holding the
/// guide as `RegisterGuide` takes it (without its pack). The guide's version decides whether
/// Polestar offers Import or Update.
pub fn import_string(id: &str, route: &Route, version: u32) -> ImportString {
    use base64::Engine as _;
    let plan = plan(route);
    let mut guide: serde_json::Map<String, serde_json::Value> = definition(id, route, version)
        .iter()
        .map(|(k, v)| ((*k).to_owned(), v.json()))
        .collect();
    let steps: Vec<serde_json::Value> = plan
        .iter()
        .map(|(title, goals)| {
            let mut step = serde_json::Map::new();
            if let Some(title) = title.as_deref().filter(|t| !t.trim().is_empty()) {
                step.insert("title".into(), title.into());
            }
            step.insert("goals".into(), goals.iter().map(Goal::json).collect());
            step.into()
        })
        .collect();
    guide.insert("steps".into(), steps.into());
    let payload = serde_json::json!({ "format": FORMAT, "license": "MIT", "guide": guide }).to_string();
    let packed = miniz_oxide::deflate::compress_to_vec_zlib(payload.as_bytes(), 9);
    let text = format!(
        "!PS1!{:08x}!{}",
        adler32(payload.as_bytes()),
        base64::engine::general_purpose::STANDARD.encode(packed)
    );
    let fits = plan.len() <= IMPORT_MAX_STEPS && text.len() <= IMPORT_MAX_CHARS && payload.len() <= IMPORT_MAX_BYTES;
    ImportString {
        text,
        steps: plan.len(),
        bytes: payload.len(),
        fits,
    }
}

fn adler32(data: &[u8]) -> u32 {
    let (mut a, mut b) = (1u32, 0u32);
    for chunk in data.chunks(5552) {
        for &byte in chunk {
            a += u32::from(byte);
            b += a;
        }
        a %= 65521;
        b %= 65521;
    }
    b << 16 | a
}

