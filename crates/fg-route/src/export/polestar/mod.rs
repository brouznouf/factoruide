use std::fmt::Write as _;

/// The pack's addon folder, and its id with Polestar (its guides are `factoruide/<guide>`).
pub const ADDON: &str = "Factoruide_Polestar";
pub(crate) const PACK_ID: &str = "factoruide";
/// The pack format written, and the first Polestar reading it: hand-ins with no accept
/// (`direct`), flight paths by node and hearths by area are read from 0.2.5 on.
const FORMAT: u32 = 3;
const NEEDS: &str = "0.2.5";
/// Polestar's Interface version (WoW Forever).
const INTERFACE: &str = "16001";

/// The files of the pack's addon, (name, content), for the guides given as (id, guide written
/// in the game's language): one leveling guide each, under the guide's name.
pub fn pack(guides: &[(String, Route)], version: &str) -> Vec<(&'static str, String)> {
    let toc = format!(
        "## Interface: {INTERFACE}\n\
         ## Title: Polestar Community: Factoruide\n\
         ## Notes: Your guides made in the Factoruide app.\n\
         ## Notes-frFR: Vos guides faits dans l'application Factoruide.\n\
         ## Author: Factoruide\n\
         ## Version: {version}\n\
         ## Category: Quests\n\
         ## Group: Polestar\n\
         ## Dependencies: Polestar\n\
         ## X-Polestar-Pack: {PACK_ID}\n\
         ## X-Polestar-Format: {FORMAT}\n\
         ## X-Polestar-Needs: {NEEDS}\n\
         ## X-License: MIT\n\
         ## X-Website: https://github.com/brouznouf/factoruide\n\
         # Generated by the Factoruide app. Do not edit: the app writes it again with the guides.\n\
         \n\
         Pack.lua\n\
         Guides.lua\n"
    );
    let pack = format!(
        "-- Generated by the Factoruide app. Do not edit.\n\
         local ADDON = ...\n\
         Polestar.RegisterPack({{ addon = ADDON, id = {}, format = {FORMAT}, title = \"Factoruide\", \
         author = \"Factoruide\", version = {}, license = \"MIT\", \
         website = \"https://github.com/brouznouf/factoruide\", \
         source = \"Guides made in the Factoruide app for your characters\" }})\n",
        lua(PACK_ID),
        lua(version)
    );
    let mut out = String::from("-- Generated by the Factoruide app. Do not edit.\n");
    for (id, route) in guides {
        out.push_str(&guide(id, route));
    }
    vec![
        ("Factoruide_Polestar.toc", toc),
        ("Pack.lua", pack),
        ("Guides.lua", out),
    ]
}

/// The race's file name in the game (Polestar's `races`).
fn race_file(id: i64) -> Option<&'static str> {
    Some(match id {
        1 => "Human",
        2 => "Orc",
        3 => "Dwarf",
        4 => "NightElf",
        5 => "Scourge",
        6 => "Tauren",
        7 => "Gnome",
        8 => "Troll",
        10 => "BloodElf",
        11 => "Draenei",
        95 | 96 => "Skyborne",
        _ => return None,
    })
}

