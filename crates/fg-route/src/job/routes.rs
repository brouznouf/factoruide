/// Every saved route.
pub fn load_routes(routes_dir: &Path) -> Result<Vec<Route>> {
    let mut files: Vec<_> = match std::fs::read_dir(routes_dir) {
        Ok(dir) => dir
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().is_some_and(|e| e == "json"))
            .collect(),
        Err(_) => Vec::new(),
    };
    files.sort();
    Ok(files
        .iter()
        .filter_map(|f| export::read_route(serde_json::from_str(&std::fs::read_to_string(f).ok()?).ok()?).ok())
        .collect())
}

pub fn save_route(routes_dir: &Path, route: &Route) -> Result<()> {
    std::fs::create_dir_all(routes_dir)?;
    let path = routes_dir.join(format!("{}.json", slug(&route.name)));
    std::fs::write(&path, serde_json::to_string_pretty(route)?)?;
    Ok(())
}

/// The data addon the apps write their guides in (never on an addon site, so that updating the
/// addon from one never erases them): `FactoruideData` holds the Lua of the guides, which the
/// guide addon runs (the same text as the web app's `/fg import`).
pub const DATA_ADDON: &str = "Factoruide_Data";

/// A Lua long string holding `text` (with a level of `=` the text does not close).
pub fn lua_long_string(text: &str) -> String {
    let mut level = 0;
    while text.contains(&format!("]{}]", "=".repeat(level))) {
        level += 1;
    }
    let eq = "=".repeat(level);
    format!("[{eq}[\n{text}]{eq}]")
}

/// Where the game's addon list shows the addons (the guide addon's and the profile's too), with
/// the profile addon's icon; the data addon is listed under the profile addon (`## Group`), as
/// the guide addon is.
const DATA_ADDON_CATEGORY: &str = "## Category: Quests\n## Category-frFR: Quêtes\n## Category-deDE: Quests\n## Category-esES: Misiones\n## Category-esMX: Misiones\n## Category-ptBR: Missões\n## Category-ruRU: Задания\n## Category-koKR: 퀘스트\n## Category-zhCN: 任务\n## Category-zhTW: 任務\n## IconTexture: Interface\\AddOns\\Factoruide_Profile\\Media\\Logo\n";

/// The data addon's files (name, content): its .toc (`interface`: the "## Interface:" line of
/// the guide addon's, `version`: the app's) and Data.lua holding `lua`, written at `time`.
pub fn data_addon_files(lua: &str, interface: &str, version: &str, time: u64) -> [(String, String); 2] {
    [
        (
            format!("{DATA_ADDON}.toc"),
            format!(
                "{interface}\n## Title: Factoruide Data\n## Notes: The guides of the Factoruide app. Written by the app: do not edit.\n{DATA_ADDON_CATEGORY}## Group: Factoruide_Profile\n## Version: {version}\nData.lua\n"
            ),
        ),
        (
            "Data.lua".to_owned(),
            format!(
                "-- Generated by the Factoruide app. Do not edit.\nFactoruideData = {}\nFactoruideDataTime = {time}\n",
                lua_long_string(lua)
            ),
        ),
    ]
}

/// Write the data addon into `dir` (see `data_addon_files`).
pub fn write_data_addon(dir: &Path, lua: &str, interface: &str, version: &str, time: u64) -> Result<()> {
    std::fs::create_dir_all(dir)?;
    for (name, content) in data_addon_files(lua, interface, version, time) {
        std::fs::write(dir.join(name), content)?;
    }
    Ok(())
}

/// The format of the guides `guides_lua` writes (each guide's `.format`; none: 1). The addon
/// refuses a guide of a format above its own, asking to update it. The addon updates on its own
/// (an addon site), the apps too: a newer addon reads every older guide, never the reverse. Bump
/// it only when an addon that reads this format can no longer follow the guide correctly (a field
/// it would misread, steps it would get wrong), not for what older addons can ignore. From format
/// 2 on, a step kind the addon does not know is shown by its text and passed: a new kind needs no
/// bump unless the guide goes wrong when it is not played.
/// 2: steps selling the bags' loot (`sell`); unknown step kinds passed.
pub const GUIDE_FORMAT: u32 = 2;

/// The Lua of guides for the addon (what `/fg import` and the data addon run): each route
/// (written as it is), with when its version was computed and its number (the addon keeps the
/// newer of two guides of a name), its format (`GUIDE_FORMAT`), the walks for its compass, and
/// the places of the trainers, vendors... in the language of the first guide.
pub fn guides_lua(
    conn: &Connection,
    overrides: &Overrides,
    edition: Edition,
    guides: Vec<(Route, u64, u32)>,
) -> Result<String> {
    use std::fmt::Write as _;
    let (mut routes, stamps): (Vec<Route>, Vec<(u64, u32)>) = guides.into_iter().map(|(r, c, v)| (r, (c, v))).unzip();
    let locale = routes
        .first()
        .and_then(|r| r.locale.clone())
        .unwrap_or_else(|| "enUS".into());
    let services = addon_walks(conn, overrides, edition, &mut routes, &Names::load(conn, &locale)?)?;
    let mut lua = export::to_lua(&routes);
    for (route, (created, version)) in routes.iter().zip(stamps) {
        let name = export::lua_str(&route.name);
        let _ = writeln!(
            lua,
            "FG.Routes[{name}].created = {created}\nFG.Routes[{name}].version = {version}\nFG.Routes[{name}].format = {GUIDE_FORMAT}"
        );
    }
    lua.push('\n');
    lua.push_str(&services);
    Ok(lua)
}

/// Write the data addon into `addon_dir` from every saved route, each written in its own
/// language, with their walks and the places of the trainers, vendors... (`addon_walks`).
pub fn write_addon_routes(
    conn: &Connection,
    overrides: &Overrides,
    edition: Edition,
    routes_dir: &Path,
    addon_dir: &Path,
    interface: &str,
) -> Result<usize> {
    let mut routes = render_routes(conn, edition, &load_routes(routes_dir)?, None)?;
    let locale = routes
        .first()
        .and_then(|r| r.locale.clone())
        .unwrap_or_else(|| "enUS".into());
    let services = addon_walks(conn, overrides, edition, &mut routes, &Names::load(conn, &locale)?)?;
    let lua = format!("{}\n{services}", export::to_lua(&routes));
    let time = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_secs());
    write_data_addon(addon_dir, &lua, interface, env!("CARGO_PKG_VERSION"), time)?;
    Ok(routes.len())
}

/// The walks of the guides (`add_walk_paths`, the world of each guide's faction), and the
/// addon's Services.lua with the names of `names`.
pub fn addon_walks(
    conn: &Connection,
    overrides: &Overrides,
    edition: Edition,
    routes: &mut [Route],
    names: &Names,
) -> Result<String> {
    let mut worlds: HashMap<Faction, World> = HashMap::new();
    for route in routes.iter_mut() {
        let world = match worlds.entry(route.faction) {
            std::collections::hash_map::Entry::Occupied(e) => e.into_mut(),
            std::collections::hash_map::Entry::Vacant(e) => e.insert(walk_world(conn, overrides, route.faction)?),
        };
        // A guide made before its walks were saved (`Editor::set_walks`).
        if route.steps.iter().all(|s| s.path.is_empty()) {
            add_walk_paths(world, route);
        }
    }
    // Where a place is does not depend on the faction.
    let world = match worlds.into_values().next() {
        Some(w) => w,
        None => walk_world(conn, overrides, Faction::Alliance)?,
    };
    Ok(services_lua(&places(conn, &world, edition, names)?))
}

/// Write the guide pack for the Polestar addon (`export::polestar`) into `dir` from every saved
/// route, each written in its own language.
pub fn write_polestar_pack(
    conn: &Connection,
    edition: Edition,
    routes_dir: &Path,
    dir: &Path,
    version: &str,
) -> Result<usize> {
    let routes = render_routes(conn, edition, &load_routes(routes_dir)?, None)?;
    let guides: Vec<(String, Route)> = routes.into_iter().map(|r| (slug(&r.name), r)).collect();
    std::fs::create_dir_all(dir)?;
    for (name, content) in export::polestar::pack(&guides, version) {
        std::fs::write(dir.join(name), content)?;
    }
    Ok(guides.len())
}

/// Write every saved route as an import string for Polestar's Import page
/// (`export::polestar::import_string`), `<guide>.txt` each in `dir`, each in its own language.
pub fn write_polestar_strings(
    conn: &Connection,
    edition: Edition,
    routes_dir: &Path,
    dir: &Path,
    _version: &str,
) -> Result<usize> {
    let routes = render_routes(conn, edition, &load_routes(routes_dir)?, None)?;
    std::fs::create_dir_all(dir)?;
    for r in &routes {
        let name = slug(&r.name);
        std::fs::write(
            dir.join(format!("{name}.txt")),
            export::polestar::import_string(&name, r, 1).text,
        )?;
    }
    Ok(routes.len())
}

/// The pack's addon folder (`export::polestar::ADDON`) when `picked` is chosen for it: `picked`
/// itself when it is that folder, else that folder in it.
pub fn polestar_addon_dir(picked: &Path) -> PathBuf {
    if picked.file_name().is_some_and(|n| n == export::polestar::ADDON) {
        picked.to_owned()
    } else {
        picked.join(export::polestar::ADDON)
    }
}

/// Add a guide (`id`, its route written in the game's language) to the Polestar pack's addon in
/// `dir`, made when missing: its file, replaced if there, the pack's other guides kept, and the
/// `.toc` loading them written again. A folder holding something else is left as it is.
/// Returns the guide's file.
pub fn add_polestar_guide(dir: &Path, id: &str, route: &Route, version: &str) -> Result<PathBuf> {
    use export::polestar::{ADDON, PACK_TAG, guide_file, guide_lua, pack_frame};
    let toc = dir.join(format!("{ADDON}.toc"));
    let ours = std::fs::read_to_string(&toc).is_ok_and(|t| t.lines().any(|l| l.trim() == PACK_TAG));
    let empty = std::fs::read_dir(dir).map_or(true, |mut d| d.next().is_none());
    if !ours && !empty {
        anyhow::bail!(
            "{} is not Factoruide's Polestar pack: choose another folder",
            dir.display()
        );
    }
    std::fs::create_dir_all(dir)?;
    let file = dir.join(guide_file(id));
    std::fs::write(&file, guide_lua(id, route))?;
    // The pack's guides before one file each, left out of the new .toc.
    let _ = std::fs::remove_file(dir.join("Guides.lua"));
    let mut guides: Vec<String> = std::fs::read_dir(dir)?
        .filter_map(|e| e.ok()?.file_name().into_string().ok())
        .filter(|n| n.strip_prefix("Guide_").and_then(|r| r.strip_suffix(".lua")).is_some())
        .collect();
    guides.sort();
    for (name, content) in pack_frame(&guides, version) {
        std::fs::write(dir.join(name), content)?;
    }
    Ok(file)
}

/// Routes written in `locale` (None: each in the language it was made in), the names of each
/// language read once from the database.
pub fn render_routes(
    conn: &Connection,
    edition: Edition,
    routes: &[Route],
    locale: Option<&str>,
) -> Result<Vec<Route>> {
    let mut names: HashMap<String, Names> = HashMap::new();
    routes
        .iter()
        .map(|r| {
            let locale = locale.or(r.locale.as_deref()).unwrap_or("enUS").to_owned();
            if !names.contains_key(&locale) {
                names.insert(locale.clone(), Names::load_for(conn, edition, &locale)?);
            }
            Ok(export::render(r, &names[&locale]))
        })
        .collect()
}

/// Lowercase ASCII identifier of a name, for file names ("Mon guide Nain !" -> "mon-guide-nain").
pub fn slug(name: &str) -> String {
    let mut out = String::new();
    for c in name.chars().flat_map(char::to_lowercase) {
        let c = match c {
            'à' | 'á' | 'â' | 'ã' | 'ä' | 'å' => 'a',
            'ç' => 'c',
            'è' | 'é' | 'ê' | 'ë' => 'e',
            'ì' | 'í' | 'î' | 'ï' => 'i',
            'ñ' => 'n',
            'ò' | 'ó' | 'ô' | 'õ' | 'ö' => 'o',
            'ù' | 'ú' | 'û' | 'ü' => 'u',
            'ý' | 'ÿ' => 'y',
            c => c,
        };
        if c.is_ascii_alphanumeric() {
            out.push(c);
        } else if !out.is_empty() && !out.ends_with('-') {
            out.push('-');
        }
    }
    let out = out.trim_end_matches('-').to_owned();
    if out.is_empty() { "route".into() } else { out }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn route(name: &str) -> Route {
        serde_json::from_value(json!({
            "name": name, "race_id": 3, "class_id": 1, "class": "Warrior",
            "faction": "Alliance", "from_level": 1, "to_level": 60, "total_time": 0.0,
            "total_time_text": "", "quests": 0, "breakdown": crate::plan::Breakdown::default(),
            "locale": "enUS", "steps": [
                { "kind": "accept", "quest": 179, "quest_name": "Dwarven Outfitters", "min_level": 1,
                  "level": 1, "time": 0.0, "target": { "kind": "npc", "id": 658, "name": "Sten Stoutarm" },
                  "map": { "ui_map": 1426, "x": 29.93, "y": 50.0 } },
            ],
        }))
        .unwrap()
    }

    fn temp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("fg-route-{}-{name}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn files(dir: &Path) -> Vec<String> {
        let mut out: Vec<String> = std::fs::read_dir(dir)
            .unwrap()
            .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())
            .collect();
        out.sort();
        out
    }

    #[test]
    fn a_picked_folder_gets_the_pack_folder_unless_it_is_the_pack() {
        let picked = Path::new("/games/AddOns");
        let pack = polestar_addon_dir(picked);
        assert_eq!(pack, picked.join(export::polestar::ADDON));
        assert_eq!(polestar_addon_dir(&pack), pack, "the pack's folder chosen again");
    }

    #[test]
    fn guides_are_added_to_the_pack_and_replaced_the_others_kept() {
        let dir = temp_dir("polestar-pack").join(export::polestar::ADDON);
        let file = add_polestar_guide(&dir, "dwarf-warrior", &route("Dwarf warrior"), "1.0.0").unwrap();
        assert_eq!(file, dir.join("Guide_dwarf-warrior.lua"));
        add_polestar_guide(&dir, "troll-mage", &route("Troll mage"), "1.0.0").unwrap();
        add_polestar_guide(&dir, "dwarf-warrior", &route("Dwarf warrior again"), "1.1.0").unwrap();
        assert_eq!(
            files(&dir),
            [
                "Factoruide_Polestar.toc",
                "Guide_dwarf-warrior.lua",
                "Guide_troll-mage.lua",
                "Pack.lua"
            ]
        );
        let guide = std::fs::read_to_string(dir.join("Guide_dwarf-warrior.lua")).unwrap();
        assert!(guide.contains("Dwarf warrior again"), "replaced");
        let toc = std::fs::read_to_string(dir.join("Factoruide_Polestar.toc")).unwrap();
        assert!(toc.contains("## Version: 1.1.0\n"));
        assert!(
            toc.ends_with("\nPack.lua\nGuide_dwarf-warrior.lua\nGuide_troll-mage.lua\n"),
            "{toc}"
        );
        std::fs::remove_dir_all(dir.parent().unwrap()).unwrap();
    }

    /// A pack written by the app before one file per guide: its old guides file goes, the toc
    /// no longer loading it.
    #[test]
    fn the_old_pack_of_one_guides_file_takes_the_new_form() {
        let dir = temp_dir("polestar-old");
        for (name, content) in export::polestar::pack(&[], "1.0.0") {
            std::fs::write(dir.join(name), content).unwrap();
        }
        std::fs::write(dir.join("Guides.lua"), "-- old").unwrap();
        add_polestar_guide(&dir, "troll-mage", &route("Troll mage"), "1.1.0").unwrap();
        assert_eq!(
            files(&dir),
            ["Factoruide_Polestar.toc", "Guide_troll-mage.lua", "Pack.lua"]
        );
        std::fs::remove_dir_all(&dir).unwrap();
    }

    #[test]
    fn a_folder_that_is_not_the_pack_is_left_as_it_is() {
        let dir = temp_dir("polestar-other");
        std::fs::write(dir.join("Factoruide_Polestar.toc"), "## Title: something else\n").unwrap();
        let err = add_polestar_guide(&dir, "dwarf-warrior", &route("Dwarf warrior"), "1.0.0").unwrap_err();
        assert!(err.to_string().contains("not Factoruide's Polestar pack"));
        assert_eq!(files(&dir), ["Factoruide_Polestar.toc"]);
        std::fs::remove_dir_all(&dir).unwrap();
    }
}
